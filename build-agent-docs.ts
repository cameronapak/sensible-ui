import { version } from "./package.json";
import { agentExamples } from "./src/pages/home.tsx";

const root = "skills/using-sensible-ui/references";
const components = `# Sensible UI components

Package version: ${version}. Generated by build-agent-docs.ts from the gallery's shared HTML examples; do not edit this file directly.

Read only the sections needed for the task. Examples may compose several components: import each one's CSS when using standalone modules. The complete root CSS import already includes core components and named layouts, but not atomic utilities or highlighted code. For scoped mode use the matching scoped CSS subpath; see [usage](usage.md). Preserve consumer theme overrides; see [design guidance](design.md).

${agentExamples
  .map(
    ([title, path, code, guidance]) => `## ${title}

CSS import: \`@faith-tools/sensible-ui/${path}\`.

${guidance}

\`\`\`html
${code.trim()}
\`\`\`
`,
  )
  .join("\n")}
## Highlighted code

CSS import: \`@faith-tools/sensible-ui/code/css\`. Browser JavaScript import: \`@faith-tools/sensible-ui/code\`. Neither is included in the core CSS import. There is no \`code/js\` or \`scoped/code\` export.

\`\`\`html
<sensible-code language="html" data-wrap="true">
  <textarea readonly><button>Save</button></textarea>
</sensible-code>
\`\`\`

Without JavaScript, the textarea stays readable. With it, highlighting, Copy, and Wrap controls are added. Escape ampersands before entity names and the opening angle bracket of any literal closing textarea tag. Code CSS is standalone, not a scoped module.
`;

const outputs = {
  [`${root}/components.md`]: components,
  [`${root}/design.md`]: `<!-- Generated from DESIGN.md by build-agent-docs.ts; do not edit directly. -->\n\n${await Bun.file("DESIGN.md").text()}`,
};

for (const [path, content] of Object.entries(outputs)) {
  if (Bun.argv.includes("--check")) {
    if (
      !(await Bun.file(path).exists()) ||
      (await Bun.file(path).text()) !== content
    ) {
      throw new Error(
        `Agent reference is stale: ${path}. Run bun run build:docs.`,
      );
    }
  } else {
    await Bun.write(path, content);
  }
}

console.log(
  `${Bun.argv.includes("--check") ? "Verified" : "Built"} agent references for ${version}`,
);
